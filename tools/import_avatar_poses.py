"""Validate/copy native image outputs, retaining the generated PNG bytes.

Usage: python tools/import_avatar_poses.py <source-records.json>
Only the Godot texture importer performs runtime compression/downsampling.
"""
from pathlib import Path
import hashlib, json, re, shutil, sys
from PIL import Image

repo=Path(__file__).resolve().parents[1]
records=json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
expected={(f'avatar_{i:02}',pose) for i in range(1,9) for pose in ('attack','hit')}
assert {(r['avatar'],r['pose']) for r in records}==expected and len(records)==16
results=[]
for record in records:
 source=Path(record['source']);im=Image.open(source);im.load()
 assert im.mode=='RGBA' and min(im.size)>=1024,source
 alpha=im.getchannel('A');hist=alpha.histogram();empty=hist[0]/(im.width*im.height)
 assert empty>.15,source
 # One native output has a 1/255 alpha corner speck (below visibility).
 # Preserve generated bytes; reject any visible/opaque background corner.
 assert all(alpha.getpixel(p)<=1 for p in [(0,0),(im.width-1,0),(0,im.height-1),(im.width-1,im.height-1)]),source
 folder=repo/'content_trickcal/avatars'/record['avatar']
 target=folder/(record['pose']+'.png')
 digest=hashlib.sha256(source.read_bytes()).hexdigest()
 if target.exists():assert hashlib.sha256(target.read_bytes()).hexdigest()==digest,'Do not overwrite a different pose'
 else:shutil.copy2(source,target)
 assert hashlib.sha256(target.read_bytes()).hexdigest()==digest
 # Use the existing, verified 2D avatar import configuration; keep source art
 # unmodified while limiting runtime texture size to 1024 with mipmaps.
 old_path=f'res://content_trickcal/avatars/{record["avatar"]}/fullbody.png'
 new_path=f'res://content_trickcal/avatars/{record["avatar"]}/{record["pose"]}.png'
 old_hash=hashlib.md5(old_path.encode()).hexdigest();new_hash=hashlib.md5(new_path.encode()).hexdigest()
 settings=(folder/'fullbody.png.import').read_text(encoding='utf-8')
 settings=re.sub(r'^uid=.*\n','',settings,flags=re.M)
 settings=settings.replace('fullbody.png',target.name).replace(old_hash,new_hash)
 settings=re.sub(r'^compress/lossy_quality=.*$', 'compress/lossy_quality=0.85',settings,flags=re.M)
 settings=settings.replace('process/size_limit=0','process/size_limit=1024')
 target.with_name(target.name+'.import').write_text(settings,encoding='utf-8')
 results.append(dict(**record,path=new_path,width=im.width,height=im.height,format=im.mode,sha256=digest,bytes=target.stat().st_size,transparent_fraction=round(empty,3),alpha_bbox=alpha.getbbox(),runtime_max_size=1024,import_quality=.85,image_model='Not exposed by native image_gen',reference_sha256=hashlib.sha256((folder/'fullbody.png').read_bytes()).hexdigest()))
dest=repo/'docs/ui-trial/avatar-capture-poses.json'
dest.write_text(json.dumps(results,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print(f'Imported {len(results)} transparent poses; source bytes unchanged; {sum(r["bytes"] for r in results)} source bytes')
for r in results:print(r['avatar'],r['pose'],r['width'],r['height'],r['transparent_fraction'])
